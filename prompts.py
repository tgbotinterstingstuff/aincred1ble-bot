SUMMARY_PROMPT = """Ты составляешь подробную ВЫЖИМКУ из материала для канала про AI-кейсы.

Это .txt файл, который читатель открывает после краткого поста. Объём — на одну страницу А4 (700-1500 слов). Структурированно, без markdown.

СТРУКТУРА (используй ровно эти секции и эмодзи-маркеры):

═════════════════════════════════════════════
[Название кейса в одну строку]
═════════════════════════════════════════════


📌 СУТЬ

Что именно сделано / в чём идея, простыми словами. 2-4 абзаца.
Объясни зачем это нужно и какую проблему решает.


🛠 КАК ЭТО РАБОТАЕТ

Технические детали, шаги, инструменты, архитектура.
Если есть промпт — приведи его дословно в кавычках.
Если есть код / команды — приведи их.


💡 РЕЗУЛЬТАТ И ВЫВОДЫ

Что получилось. Конкретные цифры, метрики, скрины (опиши словами).
Что из этого следует для читателя.


🎯 ДЛЯ КОГО ПОЛЕЗНО

Конкретные роли (разработчик, аналитик, контент-мейкер...) / задачи / контекст.
Не пиши «всем будет интересно» — конкретизируй.


⚠️ ОГРАНИЧЕНИЯ И ПОДВОДНЫЕ КАМНИ

Где не работает. Что нужно учесть. С чем автор столкнулся.
Если ограничений нет в исходнике — напиши «Не указано».


═════════════════════════════════════════════

ПРАВИЛА:
- НИКАКОГО markdown (не используй ##, **, *, _, и т.п.)
- Только обычный текст, эмодзи-маркеры и линии ═══
- Не выдумывай факты, которых нет в исходнике
- Не повторяй одно и то же в разных секциях
- Если в исходнике есть несколько частей — объедини их в единое связное описание
- Пиши на русском языке"""


# ============================================================================
# Билдеры промптов
# ============================================================================
def build_scoring_prompt(item: dict) -> str:
    return f"""{SCORING_PROMPT}

ИСТОЧНИК: {item.get('source', 'неизвестно')}
ЗАГОЛОВОК: {item.get('title', '')}
ОПИСАНИЕ: {(item.get('summary') or item.get('raw_text', ''))[:1500]}

Оценка (0-10):"""


def build_short_post_prompt(item: dict) -> str:
    content = (item.get('summary') or item.get('raw_text', ''))[:3000]
    return f"""{SHORT_POST_PROMPT}

ИСХОДНЫЙ МАТЕРИАЛ:
Заголовок: {item.get('title', '')}
Содержание:
{content}

Напиши короткий пост:"""


def build_summary_prompt(item: dict) -> str:
    content = (item.get('raw_text') or item.get('summary', ''))[:8000]
    return f"""{SUMMARY_PROMPT}

ИСХОДНЫЙ МАТЕРИАЛ:
Заголовок: {item.get('title', '')}
Источник: {item.get('source', '')}
Содержание:
{content}

Сформируй выжимку:"""


# Старая совместимость — некоторый код может ещё импортировать build_writer_prompt
def build_writer_prompt(item: dict) -> str:
    return build_short_post_prompt(item)
