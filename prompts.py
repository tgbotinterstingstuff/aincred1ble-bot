def build_scoring_prompt(item: dict) -> str:
    return f"""{SCORING_PROMPT}

ИСТОЧНИК: {item.get('source', 'неизвестно')}
ЗАГОЛОВОК: {item.get('title', '')}
ОПИСАНИЕ: {(item.get('summary') or item.get('raw_text', ''))[:1500]}

Оценка (0-10):"""


def build_short_post_prompt(item: dict) -> str:
    # Берём полный текст если есть, иначе summary. Лимит щедрый — модели нужен контекст
    # чтобы вытащить конкретику (числа, имена, инструменты), а не сочинять обтекаемый пересказ.
    content = (item.get('raw_text') or item.get('summary', ''))[:6000]
    return f"""{SHORT_POST_PROMPT}

ИСХОДНЫЙ МАТЕРИАЛ:
Заголовок: {item.get('title', '')}
Источник: {item.get('source', '')}
Содержание:
{content}

Напиши пост-разбор по структуре выше:"""


def build_summary_prompt(item: dict) -> str:
    content = (item.get('raw_text') or item.get('summary', ''))[:8000]
    return f"""{SUMMARY_PROMPT}

ИСХОДНЫЙ МАТЕРИАЛ:
Заголовок: {item.get('title', '')}
Источник: {item.get('source', '')}
Содержание:
{content}

Сформируй выжимку:"""


# Старая совместимость — некоторый код может ещё импортировать build_writer_prompt
def build_writer_prompt(item: dict) -> str:
    return build_short_post_prompt(item)
